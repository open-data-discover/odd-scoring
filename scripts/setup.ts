import { postgresPool } from '../server/store.ts';
import { reviewSchema } from '../server/reviews.ts';

const url = process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL is required');
const pool = postgresPool(url);
try {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query("SELECT pg_advisory_xact_lock(hashtext('odd-scoring-migration'))");
    if (process.argv.includes('--reset')) {
      await client.query(`
        DROP FUNCTION IF EXISTS public.odd_scoring_play(text, text, jsonb);
        DROP FUNCTION IF EXISTS odd_scoring.review_receipt(integer, text, text, integer, bytea);
        DROP TABLE IF EXISTS odd_scoring.disagreements, odd_scoring.review_points,
          odd_scoring.catalog_pairs, odd_scoring.catalog_columns,
          odd_scoring.rankings, odd_scoring.leaderboard_days, odd_scoring.cards,
          odd_scoring.sessions, odd_scoring.players, odd_scoring.column_examples,
          odd_scoring.pairs, odd_scoring.columns, odd_scoring.imports;
        DROP SCHEMA IF EXISTS odd_scoring;
      `);
    } else {
      const result = await client.query("SELECT to_regclass('odd_scoring.imports') IS NOT NULL AS legacy");
      if (result.rows[0].legacy) throw new Error('The database still has the previous schema');
    }
    await client.query(`
      CREATE SCHEMA IF NOT EXISTS odd_scoring;
      REVOKE ALL ON SCHEMA odd_scoring FROM PUBLIC;
      SET LOCAL search_path TO odd_scoring, pg_catalog;
      CREATE TABLE IF NOT EXISTS players (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL,
        name_key text NOT NULL UNIQUE
      );
      CREATE TABLE IF NOT EXISTS sessions (
        hash text PRIMARY KEY,
        player integer NOT NULL REFERENCES players(id),
        expires_at bigint NOT NULL
      );
    `);
    for (const sql of reviewSchema) await client.query(sql);
    await client.query('COMMIT');
    console.log('Join Check database is ready.');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw error;
  } finally {
    client.release();
  }
} finally {
  await pool.end();
}
